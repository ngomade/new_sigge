                    <h3>1. Présentation de l'UFD-TSI</h3>
                    <p>L'Unité de Formation Doctorale en Technologies et Sciences de l'Innovation (UFD-TSI) a été créée par Décision N⁰ 18240160 du 30 juillet 2024 de Monsieur le Recteur de l'Université d'Ebolowa, le Pr Jean Bosco ETOA ETOA, portant sur la création des Unités de Formation Doctorale au sein de certaines Grandes Écoles et Facultés de l'Université d'Ebolowa. Cette décision marque une étape importante dans le développement des activités de recherche au sein de l'Ecole Supérieure de Transport, de Logistique et de Commerce (ESTLC), où l'UFD-TSI est hébergée. L'UFD-TSI est dirigée par un coordonnateur, le Pr Jean Gaston TAMBA, par ailleurs Directeur de l'ESTLC. Il est assisté par un secrétariat administratif et scientifique.</p>

                    <h3>2. Missions et Objectifs</h3>
                    <p>L'UFD-TSI a pour missions :</p>
                    <ul>
                        <li>La promotion de la recherche scientifique dans les technologies émergentes et les sciences de l'innovation.</li>
                        <li>La formation des chercheurs, en leur offrant un encadrement académique de haut niveau afin de développer les compétences requises pour répondre aux défis actuels de la société.</li>
                        <li>Le renforcement des collaborations industrielles et académiques pour valoriser les travaux de recherche et leur application concrète.</li>
                    </ul>
                    <p>Les objectifs de l'UFD-TSI sont :</p>
                    <ul>
                        <li>Contribuer à l'innovation technologique et industrielle au niveau national et international.</li>
                        <li>Former des leaders capables de diriger des projets novateurs et durables.</li>
                        <li>Accroître l'impact sociétal des recherches en ciblant des solutions aux problématiques économiques, environnementales et sociales.</li>
                    </ul>

                    <h3>3. Domaines de Recherche</h3>
                    <p>L'UFD-TSI couvre une large gamme de domaines scientifiques et technologiques organisés autour de onze (11) laboratoires de recherche. Ces laboratoires constituent la colonne vertébrale de la formation doctorale en technologie et sciences de l'innovation :</p>
                    <ul>
                        <li>Laboratoire d'Innovation Commerciale Appliquée</li>
                        <li>Laboratoire des Systèmes Logistiques et Applications Innovantes</li>
                        <li>Laboratoire de Technologie et Systèmes Mécatroniques Intelligents</li>
                        <li>Laboratoire de Modélisation et Simulation Appliquées à l'Industrie</li>
                        <li>Laboratoire d'Informatique et Applications</li>
                        <li>Laboratoire des Sciences de la Mobilité et de la Réglementation Logistique</li>
                        <li>Laboratoire des Systèmes de Transport Intégrés en Énergie</li>
                        <li>Laboratoire des Systèmes Logistiques Miniers</li>
                        <li>Laboratoire d'Innovation pour les Technologies et Applications de l'Hydrogène</li>
                        <li>Laboratoire d'Économie et Géographie des Transports</li>
                        <li>Laboratoire de Logistique et de Transport Appliqués à l'Agriculture</li>
                    </ul>

